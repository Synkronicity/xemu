def generate_header() -> str:
    """Generate the ep_yrom.h C header source code."""
    assert len(YROM_DATA) == TOTAL_WORDS, f"Expected {TOTAL_WORDS} words, got {len(YROM_DATA)}"

    lines = [
        "/*",
        " * Motorola DSP56362 Factory Y-ROM Constants Table",
        " *",
        " * Mathematical constants defined in ATSC Standard A/52A",
        " * (Digital Audio Compression (AC-3) Standard).",
        " *",
        " * Clean-room generated via tools/gen_yrom.py.",
        " *",
        " * Copyright (c) 2026 Will Bonnett",
        " *",
        " * This library is free software; you can redistribute it and/or",
        " * modify it under the terms of the GNU Lesser General Public",
        " * License as published by the Free Software Foundation; either",
        " * version 2.1 of the License, or (at your option) any later version.",
        " */",
        "",
        "#ifndef HW_XBOX_MCPX_APU_DSP_EP_YROM_H",
        "#define HW_XBOX_MCPX_APU_DSP_EP_YROM_H",
        "",
        "#include <stdint.h>",
        "",
        "/* Index 0 is Y:$0800, length 2048 words. */",
        "// clang-format off",
        "static const uint32_t ep_yrom[2048] = {",
    ]

    for i in range(0, TOTAL_WORDS, 4):
        addr = BASE_ADDR + i
        w0 = YROM_DATA[i] & 0x00FFFFFF
        w1 = YROM_DATA[i + 1] & 0x00FFFFFF
        w2 = YROM_DATA[i + 2] & 0x00FFFFFF
        w3 = YROM_DATA[i + 3] & 0x00FFFFFF
        lines.append(f"    0x{w0:06x}, 0x{w1:06x}, 0x{w2:06x}, 0x{w3:06x}, /* ${addr:04x} */")

    lines.append("};")
    lines.append("// clang-format on")
    lines.append("")
    lines.append("#endif /* HW_XBOX_MCPX_APU_DSP_EP_YROM_H */")
    lines.append("")

    return "\n".join(lines)


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    repo_root = os.path.abspath(os.path.join(script_dir, ".."))
    default_out = os.path.join(repo_root, "hw", "xbox", "mcpx", "apu", "dsp", "ep_yrom.h")

    target_path = sys.argv[1] if len(sys.argv) > 1 else default_out

    # Validation
    if len(YROM_DATA) != TOTAL_WORDS:
        sys.exit(f"Error: YROM_DATA size mismatch: {len(YROM_DATA)} != {TOTAL_WORDS}")

    assert YROM_DATA[0] == 0x80b652, f"Word 0 invalid: 0x{YROM_DATA[0]:06x}"
    assert YROM_DATA[-1] == 0x000000, f"Word 2047 invalid: 0x{YROM_DATA[-1]:06x}"

    content = generate_header()
    encoded = content.encode("utf-8")
    md5_hash = hashlib.md5(encoded).hexdigest()

    print(f"Generated {TOTAL_WORDS} words for Motorola DSP56362 Factory Y-ROM.")
    print(f"Base Address: Y:${BASE_ADDR:04x}, End Address: Y:${BASE_ADDR + TOTAL_WORDS - 1:04x}")
    print(f"Word 0: 0x{YROM_DATA[0]:06x} | Word 2047: 0x{YROM_DATA[-1]:06x}")
    print(f"Output: {target_path}")
    print(f"MD5: {md5_hash}")

    os.makedirs(os.path.dirname(target_path), exist_ok=True)
    with open(target_path, "wb") as f:
        f.write(encoded)

    print("Success: ep_yrom.h written.")


if __name__ == "__main__":
    main()

